class WeightMonitor(Callback):
    """
    Custom diagnostic Keras Callback tracking parameters distribution metrics.

    Inspects layer-specific parameter matrix variants at structural epoch limits, 
    extracting empirical statistics (mean, variance distribution, absolute bounds) 
    to facilitate debugging vanishing or exploding gradient anomalies.
    """
    def on_epoch_end(self, epoch, logs=None):
        for layer in self.model.layers:   # type: ignore
            for w in layer.trainable_weights:
                vals = w.numpy()
                print(f"{layer.name} {w.name}: mean={vals.mean():.4f}, std={vals.std():.4f}, max={np.abs(vals).max():.4f}")


