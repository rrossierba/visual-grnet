@register_keras_serializable()
class LinearWarmup(LearningRateSchedule):
    r"""
    Serializable linear learning rate warmup schedule for backend-agnostic Keras 3.

    Linearly scales the learning rate from a baseline minimum threshold up to a targeted 
    peak value over a fixed number of absolute steps. This initialization technique prevents 
    early gradient explosion faults when optimizing recurrent architectures configured with 
    unbounded linear activations.

    The learning rate calculation at step $t$ is defined as:

    $$\eta_t = \eta_{\text{min}} + (\eta_{\text{peak}} - \eta_{\text{min}}) \times \frac{t}{T_{\text{warmup}}}$$

    Parameters
    ----------
    peak_lr : float
        The maximum target learning rate magnitude achieved at the completion of the warmup phase.
    warmup_steps : int
        The absolute step horizon constraint over which the learning rate transitions to its peak.
    min_lr : float, default 1e-5
        The starting baseline floor learning rate magnitude used to initialize the first training step.
    """
    def __init__(self, peak_lr: float, warmup_steps: int, min_lr: float = 1e-5):
        super().__init__()
        self.peak_lr = peak_lr
        self.warmup_steps = warmup_steps
        self.min_lr = min_lr

    def __call__(self, step: tf.Tensor) -> tf.Tensor:
        """
        Compute the dynamic operational learning rate matching the active training step pointer.

        Parameters
        ----------
        step : tf.Tensor
            The scalar tracking step pointer parsed from the current global optimizer cycle.

        Returns
        -------
        tf.Tensor
            A scalar tensor tracking the computed objective learning rate value.
        """
        step = ops.cast(step, 'float32') # type: ignore
        warmup_steps = float(self.warmup_steps)

        warmup_lr = self.min_lr + (self.peak_lr - self.min_lr) * (step / warmup_steps)
        return ops.where(step < warmup_steps, warmup_lr, self.peak_lr) # type: ignore

    def get_config(self) -> dict:
        """
        Serialize the schedule parameter constraints into a metadata mapping.

        Returns
        -------
        dict
            A key-value serialization dictionary dictionary mapping tracking variables.
        """
        return {
            'peak_lr': self.peak_lr,
            'warmup_steps': self.warmup_steps,
            'min_lr': self.min_lr,
        }


@register_keras_serializable()
class WarmupCosineDecay(LearningRateSchedule):
    r"""
    Serializable Learning Rate schedule with Linear Warmup followed by Cosine Decay 
    for backend-agnostic Keras 3.

    Parameters
    ----------
    peak_lr : float
        Maximum target learning rate achieved at the end of warmup.
    warmup_steps : int
        Number of steps for the linear warmup phase.
    decay_steps : int
        Number of steps for the cosine decay phase after warmup.
    min_lr : float, default 1e-5
        Baseline learning rate floor used at start of warmup and end of decay.
    """
    def __init__(
        self, 
        peak_lr: float, 
        warmup_steps: int, 
        decay_steps: int, 
        min_lr: float = 1e-5,
        **kwargs
    ):
        super().__init__(**kwargs)
        self.peak_lr = peak_lr
        self.warmup_steps = warmup_steps
        self.decay_steps = decay_steps
        self.min_lr = min_lr

    def __call__(self, step):
        step = ops.cast(step, 'float32')
        warmup_steps = float(self.warmup_steps)
        decay_steps = float(self.decay_steps)

        warmup_lr = self.min_lr + (self.peak_lr - self.min_lr) * (step / warmup_steps)

        decay_step = ops.clip(step - warmup_steps, 0.0, decay_steps)
        cosine_decay = 0.5 * (1.0 + ops.cos(math.pi * (decay_step / decay_steps)))
        decay_lr = self.min_lr + (self.peak_lr - self.min_lr) * cosine_decay

        return ops.where(step < warmup_steps, warmup_lr, decay_lr)

    def get_config(self) -> dict:
        config = super().get_config()
        config.update({
            'peak_lr': self.peak_lr,
            'warmup_steps': self.warmup_steps,
            'decay_steps': self.decay_steps,
            'min_lr': self.min_lr,
        })
        return config


