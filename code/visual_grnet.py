def build_network(network_params: Union[NetworkParams, None] = None, bias_initializer: Union[np.ndarray, None] = None) -> Model:
    """
    Instantiate and compile the Visual GRNet (VGN) sequential network model.

    This function builds a Keras Functional Model mapping structural pipelines including: 
    an optional multi-layer linear projection adapter with an explicit residual skip connection 
    and layer normalization, a masked recurrent tracking block (LSTM or Bidirectional LSTM), 
    a sequential token-level scoring mechanism (AttentionWeights), and a dense classification 
    head initialized with frequency-derived empirical bias priors.

    Parameters
    ----------
    network_params : Optional[NetworkParams], default None
        The configuration dataclass tracking topological variables, structural layer hyperparameters, 
        and optimization rules. If None, instantiates a default structural instance.
    bias_initializer : Optional[np.ndarray], default None
        A 1D array of shape (num_classes,) containing data-driven empirical joint frequency 
        weights to initialize output biases. Allocates zeros if not provided.

    Returns
    -------
    keras.models.Model
        A compiled instance of the Keras Functional Model ready for optimization loops.
    """    
    if network_params is None:
        network_params = NetworkParams(model_name='visual-grnet')

    embedding_dim = network_params.embedding_dim
    recurrent_params = network_params.recurrent
    optimizer_params = network_params.optimizer
    adapter_params = network_params.adapter
    dataset_params = network_params.dataset
    
    inputs = Input(shape=(dataset_params.max_sequence_dim, embedding_dim), name='input')

    if adapter_params.use_adapter:
        adapt_factor = adapter_params.adapt_factor
        adapt_dropout = adapter_params.adapt_dropout
        
        x = Dense(embedding_dim * adapt_factor, activation=adapter_params.activation, name='adapter_up')(inputs)
        if adapt_dropout > 0:
            x = Dropout(adapt_dropout, name='dropout_1')(x)
            
        x = Dense(embedding_dim * adapt_factor, activation=adapter_params.activation, name='adapter_h')(x)
        if adapt_dropout > 0:
            x = Dropout(adapt_dropout, name='dropout_2')(x)
            
        x = Dense(embedding_dim, name='adapter_down')(x)
        x = x + inputs
        x = LayerNormalization(name='layer_norm')(x)
    else:
        x = inputs
    
    mask = ops.any(ops.not_equal(inputs, -100.0), axis=-1)
    
    lstm = LSTM(
        activation=recurrent_params.activation,
        units=recurrent_params.units,
        dropout=recurrent_params.dropout,
        recurrent_dropout=recurrent_params.recurrent_dropout,
        return_sequences=True,
        name='lstm'
    )

    if network_params.use_bidirectional:
        recurrent_layer = Bidirectional(lstm)(x, mask=mask)
    else:
        recurrent_layer = lstm(x, mask=mask)
    
    attention_weights = AttentionWeights(dataset_params.max_sequence_dim, name='attention_weights')(recurrent_layer, mask=mask)
    context_vector = ContextVector()([recurrent_layer, attention_weights])

    if bias_initializer is None:
        bias_initializer = np.zeros(shape=(dataset_params.num_classes,))

    outputs = Dense(
        dataset_params.num_classes, 
        activation='sigmoid', 
        kernel_regularizer=network_params.output_regularizer,
        bias_initializer=Constant(bias_initializer), # type: ignore
        name='output'
    )(context_vector)

    model = Model(inputs=inputs, outputs=outputs, name=network_params.model_name)

    if optimizer_params.lr_scheduler.use_warmup and not optimizer_params.lr_scheduler.use_decay:
        lr_schedule = LinearWarmup(
            peak_lr=optimizer_params.learning_rate,
            warmup_steps=optimizer_params.lr_scheduler.warmup_epochs * optimizer_params.lr_scheduler.steps_per_epoch,
            min_lr=optimizer_params.lr_scheduler.min_lr
        )
    elif optimizer_params.lr_scheduler.use_warmup and optimizer_params.lr_scheduler.use_decay:
        lr_schedule = WarmupCosineDecay(
            peak_lr=optimizer_params.learning_rate,
            warmup_steps=optimizer_params.lr_scheduler.warmup_epochs * optimizer_params.lr_scheduler.steps_per_epoch,
            decay_steps=optimizer_params.lr_scheduler.steps_per_epoch * (50 - optimizer_params.lr_scheduler.warmup_epochs),
            min_lr=optimizer_params.lr_scheduler.min_lr
        )
    else:
        lr_schedule = optimizer_params.learning_rate

    model.compile(
        optimizer=Adam(
            learning_rate=lr_schedule, # type: ignore
            clipnorm=optimizer_params.clipnorm,
        ), 
        loss=network_params.loss_function,
        metrics=[
            AUC(
                name='pr_auc', 
                multi_label=True, 
                num_labels=dataset_params.num_classes, 
                curve='PR', 
                num_thresholds=500
            )
        ]
    )

    return model

