def evaluate(y_pred: np.ndarray, y_true: np.ndarray, threshold: float = 0.5, print_results: bool = False) -> dict:
    """
    Evaluate multi-label sequence classification performance across multiple core metrics.

    Applies a hard binarization decision boundary threshold to output continuous distributions,
    computing exact match criteria, dimension-wise label correctness, and macro-averaged 
    precision, recall, and F1 configurations.

    Parameters
    ----------
    y_pred : np.ndarray
        A 2D array tracking the predicted confidence coordinates mapping target classes.
    y_true : np.ndarray
        A 2D multi-hot array tracking true target goal intersections.
    threshold : float, default 0.5
        The hard logical activation scalar threshold separating negative and positive states.
    print_results : bool, default False
        If True, outputs a formatted performance breakdown table to standard output.

    Returns
    -------
    dict
        A summary dictionary mapping calculated classification performance criteria.
    """    
    y_bin = (y_pred >= threshold).astype(int)

    metrics = {
        'exact_accuracy':      accuracy_score(y_true, y_bin),
        'mean_label_accuracy': (y_true == y_bin).mean(axis=0).mean(),
        'precision_macro':     precision_score(y_true, y_bin, average='macro', zero_division=0),
        'recall_macro':        recall_score(y_true, y_bin, average='macro', zero_division=0),
        'f1_macro':            f1_score(y_true, y_bin, average='macro', zero_division=0),
        'pr_auc_macro':        average_precision_score(y_true, y_pred, average=None).mean(), # type: ignore
        'avg_true_positive':   y_true.sum(axis=1).mean(),
        'avg_pred_positive':   y_bin.sum(axis=1).mean(),
    }

    if print_results:
        print(f'Metrics (threshold={threshold})')
        print('-' * 60)
        print(f"Exact match accuracy:\t{metrics['exact_accuracy']:.4f}")
        print(f"Mean label accuracy:\t{metrics['mean_label_accuracy']:.4f}")
        print(f"Precision (macro):\t{metrics['precision_macro']:.4f}")
        print(f"Recall (macro):\t\t{metrics['recall_macro']:.4f}")
        print(f"F1 (macro):\t\t{metrics['f1_macro']:.4f}")
        print(f"PR-AUC (macro):\t\t{metrics['pr_auc_macro']:.4f}")
        print(f"\nMean true positives per sample:      {metrics['avg_true_positive']:.2f}")
        print(f"Mean predicted positives per sample: {metrics['avg_pred_positive']:.2f}")

    return metrics


def get_bias_initialization(y_train: np.ndarray) -> np.ndarray: 
    """
    Derive optimal base frequency prior logit biases to stabilize network initialization.

    Calculates sample-wise positive activation frequencies across training sets and applies 
    the inverse sigmoid mapping transformation. This initialization guarantees that early cross-entropy 
    gradients reflect empirical label distributions, accelerating convergence in imbalanced setups.

    Parameters
    ----------
    y_train : np.ndarray
        A 2D training target array tracking historical multi-hot label intersections.

    Returns
    -------
    np.ndarray
        A 1D float32 log-odds bias array of shape (num_classes,) used to initialize output Dense layers.
    """
    print('Extracting empirical distribution prior bias initialization...')
    pos_freq = np.mean(y_train, axis=0)  
    
    # Clippa i limiti numerici per evitare errori di instabilità matematica log(0) o divisioni per zero
    pos_freq = np.clip(pos_freq, 1e-7, 1.0 - 1e-7)
    bias_init = np.log(pos_freq / (1.0 - pos_freq))
    return bias_init


@register_keras_serializable()
class WeightedBCE(Loss):
    """
    Custom frequency-weighted Binary Cross-Entropy loss for backend-agnostic Keras 3.

    Balances binary classification objective functions by scaling positive and negative losses 
    separately based on empirical class distribution ratios. This prevents dominant negative labels 
    from washing out scarce positive signals in sparse multi-hot spaces.

    Parameters
    ----------
    pos_weights : np.ndarray
        A 1D array of shape (num_classes,) containing penalty scalars applied to positive misses.
    neg_weights : np.ndarray
        A 1D array of shape (num_classes,) containing penalty scalars applied to negative misses.
    name : str, default "weighted_bce"
        The organizational string identifier tagging the structural loss instance.
    """
    def __init__(
        self,
        pos_weights: np.ndarray,  
        neg_weights: np.ndarray,
        name: str = "weighted_bce",
        **kwargs
    ):
        super().__init__(name=name, **kwargs)
        self.pos_weights = pos_weights  
        self.neg_weights = neg_weights
        self._pos_weights_tensor = ops.convert_to_tensor(pos_weights, dtype='float32')  
        self._neg_weights_tensor = ops.convert_to_tensor(neg_weights, dtype='float32')  

    def call(self, y_true: tf.Tensor, y_pred: tf.Tensor) -> tf.Tensor:
        """
        Compute the dynamic objective loss tensor mapping input batch matrices.

        Parameters
        ----------
        y_true : tf.Tensor
            The target true classification matrix tracking multi-hot ground truth labels.
        y_pred : tf.Tensor
            The network forward pass continuous output logit activation matrix.

        Returns
        -------
        tf.Tensor
            A scalar tensor tracking the aggregated weighted categorical cross-entropy loss value.
        """
        y_true = ops.cast(y_true, 'float32') # type: ignore
        y_pred = ops.cast(y_pred, 'float32') # type: ignore
        
        y_pred = ops.clip(y_pred, 1e-7, 1.0 - 1e-7) # type: ignore

        bce = -(
            self._pos_weights_tensor * y_true * ops.log(y_pred)
            + self._neg_weights_tensor * (1.0 - y_true) * ops.log(1.0 - y_pred)
        )
        return ops.mean(bce) # type: ignore

    def get_config(self) -> dict:
        """
        Serialize the class configuration parameters into standard Python datatypes.

        Returns
        -------
        dict
            A tracking key-value dictionary containing serialized loss parameters.
        """
        config = super().get_config()
        config.update({
            "pos_weights": self.pos_weights.tolist(), 
            "neg_weights": self.neg_weights.tolist(),
        })
        return config

    @classmethod
    def from_config(cls, config: dict) -> 'WeightedBCE':
        """
        Instantiate an identical operational object recovery layout from configuration maps.

        Parameters
        ----------
        config : dict
            The key-value parameters dictionary retrieved from the serialization parser.

        Returns
        -------
        WeightedBCE
            A fully restored, operational custom Loss instance.
        """
        config["pos_weights"] = np.array(config["pos_weights"])  
        config["neg_weights"] = np.array(config["neg_weights"])
        return cls(**config)
    

def calculate_frequencies(label_npz: Union[str, Path]) -> tuple[np.ndarray, np.ndarray]:
    """
    Extract dimensional positive and negative prior occurrence frequencies from an NPZ file.

    Loads a compressed training archive, reconstructs stacked multi-hot training targets, 
    and applies axis-wise counts to determine structural scaling constants for balanced training.

    Parameters
    ----------
    label_npz : str or pathlib.Path
        The filepath pointing to the compressed precomputed training embeddings archive.

    Returns
    -------
    positive_frequencies : np.ndarray
        A 1D array tracking the fractional occurrence rate of positive labels per class dimension.
    negative_frequencies : np.ndarray
        A 1D array tracking the fractional occurrence rate of negative labels per class dimension.
    """
    train_embeddings = np.load(label_npz)
    
    # Vectorized list comprehension mapping to optimize memory allocations over historical iterations
    labels = np.stack([train_embeddings[f'goal_{seq}'] for seq in train_embeddings['seq_names']])
    n_samples = labels.shape[0]
    
    positive_frequencies = np.sum(labels, axis=0) / n_samples  
    negative_frequencies = 1.0 - positive_frequencies   

    return positive_frequencies, negative_frequencies