class StaticProgressLogger(Callback):
    """
    Custom Keras Callback for standardized experiment logging and high-resolution profiling.

    Tracks absolute operational wall-clock execution limits, displays structural metrics 
    separated by training/validation contexts, and profiles host batch computation times 
    using high-resolution hardware timers (`time.perf_counter`).

    Parameters
    ----------
    batch_logging : bool, default False
        If True, activates sub-epoch profiling loops at discrete step intervals.
    batch_logging_steps : Optional[int], default None
        The scale factor coefficient tracking the frequency of intra-epoch printing.
    """
    def __init__(self, batch_logging: bool = False, batch_logging_steps: Union[int, None] = None):
        if batch_logging:
            self.batch_logging = batch_logging
            self.batch_logging_steps = batch_logging_steps
        else:
            self.batch_logging = self.batch_logging_steps = None
        super().__init__()

    def on_train_begin(self, logs=None):
        self.step_times = []
        print(f"\n{'='*60}")
        print(f"BEGIN TRAINING: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        print(f"{'='*60}\n", flush=True)

    def on_epoch_begin(self, epoch, logs=None):
        self.epoch_start_time = time.time()
        print(f'\nStarting Epoch {epoch + 1:02d}')

    def on_epoch_end(self, epoch, logs=None):
        duration = time.time() - self.epoch_start_time
        now = datetime.now().strftime('%H:%M:%S')

        train_metrics_str = ''
        val_metrics_str = ''
        info_str = f"[{now}]\t Epoch {epoch + 1:02d} | Time: {duration:6.2f}s |"
        
        if isinstance(logs, dict):
            for metric, value in logs.items():
                metric_str = f"{value:.6f}" if isinstance(value, float) else value
                if metric.startswith('val'):
                    val_metrics_str += f"{metric}: {metric_str} | "
                else:
                    train_metrics_str += f"{metric}: {metric_str} | "
            
            info_str += f"{train_metrics_str} || {val_metrics_str}"
        
        print(info_str, flush=True)
        
        arr = np.array(self.step_times)
        if arr.size > 0:
            print(f"\t\t\tTime — mean: {arr.mean()*1000:.2f} ms | "
                  f"min: {arr.min()*1000:.2f} ms | max: {arr.max()*1000:.2f} ms")
        self.step_times = []  

    def on_train_end(self, logs=None):
        print(f"\n{'='*60}")
        print(f"END TRAINING: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        print(f"{'='*60}\n", flush=True)
    
    def on_train_batch_begin(self, batch, logs=None):
        self._batch_start = time.perf_counter()
    
    def on_train_batch_end(self, batch, logs=None):
        elapsed = time.perf_counter() - self._batch_start
        self.step_times.append(elapsed)
        if self.batch_logging is not None and self.batch_logging_steps is not None:
            if batch % self.batch_logging_steps == 0:
                if batch == 0:
                    print(f"Batch {batch} — {elapsed*1000:.2f} ms")
                else:
                    str_losses = '' 
                    if isinstance(logs, dict):
                        for metric, value in logs.items():
                            metric_str = f"{value:.6f}" if isinstance(value, float) else value
                            str_losses += f"{metric}: {metric_str} | "

                    print(f"Batch {batch} — {sum(self.step_times[-self.batch_logging_steps:])*1000:.2f} ms - {str_losses}", flush=True)


